import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const siteRoot = path.resolve(__dirname, '..');
const repoRoot = path.resolve(siteRoot, '..');
const distDir = path.join(siteRoot, 'dist');
const redirectsPath = path.join(siteRoot, 'src/data/redirects.json');
const outConfPath = path.join(repoRoot, 'ops/nginx/householdrebates-redirects.conf');

const redirects = JSON.parse(fs.readFileSync(redirectsPath, 'utf8'));
if (!Array.isArray(redirects)) {
  throw new Error('src/data/redirects.json must be an array');
}

function isBuiltUrl(urlPath) {
  if (!fs.existsSync(distDir)) return true;
  const rel = urlPath === '/' ? 'index.html' : path.join(urlPath.replace(/^\/|\/$/g, ''), 'index.html');
  return fs.existsSync(path.join(distDir, rel));
}

const lines = [
  '# Auto-generated by site/scripts/build-redirects.mjs — do not edit by hand.',
  '# Include inside the householdrebates.com.au server block only after Guri approves.',
];

for (const entry of redirects) {
  const { from, to, code, reason, addedOn } = entry;
  if (!from || !from.startsWith('/') || !from.endsWith('/')) {
    throw new Error(`Invalid redirect "from" path: "${from}"`);
  }
  if (code !== 301 && code !== 410) {
    throw new Error(`Invalid redirect status code ${code} for "${from}" (allowed: 301, 410)`);
  }
  if (!reason || !addedOn) {
    throw new Error(`Redirect "${from}" must include reason and addedOn`);
  }
  if (fs.existsSync(distDir) && isBuiltUrl(from)) {
    throw new Error(`Redirect "from" URL "${from}" is still a built page in dist/`);
  }
  if (code === 301) {
    if (!to || !to.startsWith('/') || !to.endsWith('/')) {
      throw new Error(`301 redirect "${from}" requires valid trailing-slash "to" path`);
    }
    if (fs.existsSync(distDir) && !isBuiltUrl(to)) {
      throw new Error(`Redirect "to" URL "${to}" is not a built page in dist/`);
    }
    lines.push(`location = ${from} { return 301 ${to}; }`);
  } else {
    lines.push(`location = ${from} { return 410; }`);
  }
}

fs.mkdirSync(path.dirname(outConfPath), { recursive: true });
fs.writeFileSync(outConfPath, `${lines.join('\n')}\n`, 'utf8');
console.log(`build-redirects: ${redirects.length} redirects written to ops/nginx/householdrebates-redirects.conf`);
